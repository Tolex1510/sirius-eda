"""Server-side boundaries for operations and safety-critical claims."""
import re


def guard_reply(question):
    if re.search(r'аллерг|алерг|непереносим|точно безопасн',question,re.I):
        return ('Я могу показать заявленный состав блюда, но не могу гарантировать безопасность при аллергии '
                'или отсутствие следов аллергенов. Откройте состав в карточке и уточните информацию у кухни; '
                'веганская рецептура сама по себе не является гарантией отсутствия аллергенов.')
    if re.search(r'SECRET_KEY|чуж(?:ие|их|ой).*плат|чуж(?:ие|их|ой).*заказ|пользовател[яю]\s*\d+|список клиентов|прав[аы].*admin',question,re.I):
        return 'Я не раскрываю секреты, данные других пользователей и не меняю права доступа. Могу помочь с меню и вашими собственными заказами.'
    if re.search(r'^\s*(?:пожалуйста[,\s]+)?(?:отмени|оплати|спиши|верни|выдай)\b',question,re.I):
        return 'Я не провожу оплату, возврат и отмену за вас. Эти действия выполняются в разделе «Мои заказы»; отмена доступна до передачи заказа в путь.'
    if re.search(r'почему.*заказ.*отменили',question,re.I):
        return 'Уточните номер отменённого заказа. По общему вопросу я не могу достоверно определить причину отмены.'
    if re.search(r'сколько.*минут.*достав|когда.*точно.*деньг|когда.*точно.*возврат',question,re.I):
        return 'Точное время доставки или зачисления возврата неизвестно. Фактический статус можно посмотреть в разделе «Мои заказы».'
    return None
